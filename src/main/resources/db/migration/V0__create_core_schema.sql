CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255),
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    phone VARCHAR(255),
    base_currency VARCHAR(255)
);

CREATE TABLE wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(255) NOT NULL,
    type VARCHAR(32) NOT NULL,
    balance NUMERIC(19, 4) NOT NULL,
    CONSTRAINT uq_wallet_user_name UNIQUE (user_id, name),
    CONSTRAINT wallets_type_check
        CHECK (type IN ('BANK', 'CASH', 'CREDIT_CARD', 'E_WALLET'))
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(255) NOT NULL,
    icon VARCHAR(255),
    type VARCHAR(32) NOT NULL,
    CONSTRAINT uq_category_user_name UNIQUE (user_id, name),
    CONSTRAINT categories_type_check CHECK (type IN ('INCOME', 'EXPENSE'))
);

CREATE TABLE goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    wallet_id BIGINT NOT NULL REFERENCES wallets(id),
    name VARCHAR(255) NOT NULL,
    target_amount NUMERIC(19, 4) NOT NULL,
    current_amount NUMERIC(19, 4) NOT NULL,
    deadline DATE,
    status VARCHAR(32) NOT NULL,
    CONSTRAINT goals_status_check
        CHECK (status IN ('IN_PROGRESS', 'ACHIEVED', 'CANCELLED'))
);

CREATE TABLE debts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    wallet_id BIGINT NOT NULL REFERENCES wallets(id),
    counterpart_name VARCHAR(255) NOT NULL,
    type VARCHAR(32) NOT NULL,
    total_amount NUMERIC(19, 4) NOT NULL,
    remaining_amount NUMERIC(19, 4) NOT NULL,
    due_date DATE,
    status VARCHAR(32) NOT NULL,
    note TEXT,
    CONSTRAINT debts_type_check CHECK (type IN ('LEND', 'BORROW')),
    CONSTRAINT debts_status_check CHECK (status IN ('PENDING', 'COMPLETED', 'OVERDUE'))
);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    wallet_id BIGINT NOT NULL REFERENCES wallets(id),
    category_id BIGINT NOT NULL REFERENCES categories(id),
    goal_id BIGINT REFERENCES goals(id),
    debt_id BIGINT REFERENCES debts(id),
    amount NUMERIC(19, 4) NOT NULL,
    type VARCHAR(32) NOT NULL,
    note TEXT,
    transaction_date TIMESTAMP NOT NULL,
    CONSTRAINT transactions_type_check CHECK (type IN ('INCOME', 'EXPENSE', 'TRANSFER'))
);
