CREATE TABLE ai_extractions (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    source VARCHAR(20) NOT NULL,
    merchant_key VARCHAR(200),
    merchant_label VARCHAR(200),
    proposed_category_id BIGINT,
    transaction_type VARCHAR(20) NOT NULL,
    amount NUMERIC(19, 4),
    currency VARCHAR(3),
    prompt_version VARCHAR(100) NOT NULL,
    model_version VARCHAR(150) NOT NULL,
    provider VARCHAR(50) NOT NULL,
    confidence_score NUMERIC(5, 4) NOT NULL,
    confidence_level VARCHAR(20) NOT NULL,
    confidence_reasons VARCHAR(1000) NOT NULL,
    confidence_profile VARCHAR(100) NOT NULL,
    confidence_calibrated BOOLEAN NOT NULL DEFAULT FALSE,
    rule_applied BOOLEAN NOT NULL DEFAULT FALSE,
    requires_clarification BOOLEAN NOT NULL DEFAULT TRUE,
    locale VARCHAR(35) NOT NULL,
    time_zone VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_ai_extractions_user_created
    ON ai_extractions(user_id, created_at DESC);

CREATE TABLE ai_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    extraction_id UUID NOT NULL REFERENCES ai_extractions(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    proposed_category_id BIGINT,
    confirmed_category_id BIGINT,
    confirmed_transaction_type VARCHAR(20) NOT NULL,
    outcome VARCHAR(20) NOT NULL,
    remember_rule BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_ai_feedback_user_created
    ON ai_feedback(user_id, created_at DESC);

CREATE TABLE categorization_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    merchant_key VARCHAR(200) NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,
    category_id BIGINT NOT NULL,
    confirmation_count INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_categorization_rule_user_merchant_type
        UNIQUE (user_id, merchant_key, transaction_type)
);

CREATE INDEX idx_categorization_rules_user_type
    ON categorization_rules(user_id, transaction_type, updated_at DESC);
