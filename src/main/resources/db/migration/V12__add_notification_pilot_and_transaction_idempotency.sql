CREATE TABLE notification_pilot_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    metric_date DATE NOT NULL,
    source VARCHAR(30) NOT NULL,
    parser_version VARCHAR(50) NOT NULL,
    observed_count BIGINT NOT NULL DEFAULT 0,
    parsed_count BIGINT NOT NULL DEFAULT 0,
    parse_failure_count BIGINT NOT NULL DEFAULT 0,
    local_duplicate_count BIGINT NOT NULL DEFAULT 0,
    uploaded_count BIGINT NOT NULL DEFAULT 0,
    server_replay_count BIGINT NOT NULL DEFAULT 0,
    possible_duplicate_count BIGINT NOT NULL DEFAULT 0,
    confirmed_count BIGINT NOT NULL DEFAULT 0,
    rejected_false_positive_count BIGINT NOT NULL DEFAULT 0,
    rejected_duplicate_count BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_notification_pilot_metric
        UNIQUE (user_id, metric_date, source, parser_version)
);

CREATE INDEX idx_notification_pilot_metrics_user_date
    ON notification_pilot_metrics(user_id, metric_date DESC);
